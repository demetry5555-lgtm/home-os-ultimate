import { makePage, makeHelpers, setupOwner, finish, sleep } from './e2e5common.mjs'

const { browser, page } = await makePage()
const h = makeHelpers(page)
const today = new Date().toISOString().slice(0, 10)
const clearInput = sel => page.$eval(sel, el => {
  Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(el, '')
  el.dispatchEvent(new Event('input', { bubbles: true }))
})
const typeSearch = val => page.$eval('input', (el, v) => {
  Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(el, v)
  el.dispatchEvent(new Event('input', { bubbles: true }))
}, val)

try {
  await setupOwner(page, h, true)   // ends signed in as owner, Sara already joined

  // owner uploads a family doc + an owner-only doc
  await h.go('#/home/documents')
  await h.clickButton('Upload file')
  await sleep(300)
  let fileInput = await page.$('form input[type=file]')
  await fileInput.uploadFile('/tmp/tiny.png')
  let inp = await page.$$('form input:not([type=file])')
  await inp[0].type('Family photo')
  await h.selectByText(0, 'Photo')
  await h.clickButton('Upload file', true)
  await sleep(800)
  await h.clickButton('Upload file')
  await sleep(300)
  fileInput = await page.$('form input[type=file]')
  await fileInput.uploadFile('/tmp/lease.pdf')
  inp = await page.$$('form input:not([type=file])')
  await inp[0].type('Lease contract')
  await h.selectByText(0, 'Contract')
  await h.selectByText(1, 'Owner only')
  await h.clickButton('Upload file', true)
  await sleep(800)
  await h.signOut()

  // --- Sara: member doc isolation ---
  await h.signIn('sara@home.local', 'sara-pass-123')
  await h.go('#/home/documents')
  let memberDocs = await h.bodyText()
  h.check('member sees family document', memberDocs.includes('Family photo'))
  h.check('member cannot see owner-only document', !memberDocs.includes('Lease contract'))

  // --- Sara creates a request ---
  await h.go('#/home/requests')
  await h.clickButton('New request')
  await sleep(300)
  inp = await page.$$('form input:not([type=file])')
  await inp[0].type('New phone')
  await inp[1].type('My phone broke')
  await inp[2].type('300')
  await h.clickButton('Submit request')
  await sleep(700)
  h.check('member request created', (await h.bodyText()).includes('New phone'))
  await h.signOut()

  // --- owner: invitation notification, approve request, assign task due today ---
  await h.signIn('owner@home.local', 'owner-pass-123')
  await h.go('#/home/notifications')
  h.check('owner notified of invitation acceptance', (await h.bodyText()).includes('Invitation accepted'))
  await h.go('#/home/requests')
  await page.$$eval('a', as => as.find(a => a.textContent.includes('New phone'))?.click())
  await sleep(700)
  await h.clickButton('Approve')
  await sleep(400)
  await page.$$eval('button', bs => bs.filter(b => b.textContent.trim() === 'Approve' && !b.disabled).pop()?.click())
  await sleep(800)
  h.check('request approved', (await h.bodyText()).includes('Approved'))
  await h.go('#/home/tasks')
  await h.clickButton('New task')
  await sleep(300)
  inp = await page.$$('form input:not([type=date]):not([type=checkbox])')
  await inp[0].type('Homework check')
  await h.selectByText(0, 'Sara')
  await h.setReactDate('form input[type=date]', 1, today)
  await h.clickButton('Create')
  await sleep(800)
  h.check('task assigned', (await h.bodyText()).includes('Homework check'))
  await h.signOut()

  // --- Sara: badge, notifications, reminder, mark all read ---
  await h.signIn('sara@home.local', 'sara-pass-123')
  const badge = await page.evaluate(() => document.querySelector('a[href*="notifications"] span')?.textContent ?? '')
  h.check('unread badge shows count', badge === '2')
  await h.go('#/home/notifications')
  await sleep(600)
  let notifText = await h.bodyText()
  h.check('request decision notification', notifText.includes('Request approved'))
  h.check('task assignment notification', notifText.includes('New task assigned'))
  h.check('due-today reminder shown', notifText.includes('Due today'))
  await h.clickButton('Mark all read')
  await sleep(800)
  const badgeAfter = await page.evaluate(() => document.querySelector('a[href*="notifications"] span')?.textContent ?? '')
  h.check('badge clears after mark all read', badgeAfter === '')
  await page.screenshot({ path: '/downloads/homeos-22-notifications.png' })

  // --- settings: Sara disables task notifications ---
  await h.clickButton('⚙')
  await sleep(400)
  const boxes = await page.$$('input[type=checkbox]')
  await boxes[1].click()   // task kind
  await sleep(500)
  await h.signOut()
  await h.signIn('owner@home.local', 'owner-pass-123')
  await h.go('#/home/tasks')
  await h.clickButton('New task')
  await sleep(300)
  inp = await page.$$('form input:not([type=date]):not([type=checkbox])')
  await inp[0].type('Second task')
  await h.selectByText(0, 'Sara')
  await h.clickButton('Create')
  await sleep(800)
  await h.signOut()
  await h.signIn('sara@home.local', 'sara-pass-123')
  await h.go('#/home/notifications')
  await sleep(500)
  h.check('disabled kind produces no notification', !(await h.bodyText()).includes('Second task'))

  // --- global search (as Sara) ---
  await h.go('#/home/search')
  await page.type('input', 'Family photo')
  await sleep(800)
  h.check('search finds document', (await h.bodyText()).includes('Family photo'))
  await typeSearch('Homework')
  await sleep(800)
  h.check('search finds task', (await h.bodyText()).includes('Homework check'))
  await typeSearch('Lease')
  await sleep(800)
  h.check('member search cannot find owner-only document', !(await h.bodyText()).includes('Lease contract'))
  await h.signOut()

  // --- owner search ---
  await h.signIn('owner@home.local', 'owner-pass-123')
  await h.go('#/home/search')
  await page.type('input', 'Lease')
  await sleep(800)
  h.check('owner search finds owner-only document', (await h.bodyText()).includes('Lease contract'))
  await typeSearch('Sara')
  await sleep(800)
  h.check('search finds member', (await h.bodyText()).includes('Sara'))
  await typeSearch('phone')
  await sleep(800)
  h.check('search finds request', (await h.bodyText()).includes('New phone'))
  await page.screenshot({ path: '/downloads/homeos-23-search.png' })
} catch (err) {
  console.log('CRASH:', err.message)
  await page.screenshot({ path: '/downloads/e2e5b-crash.png' })
  console.log((await h.bodyText()).slice(0, 300))
} finally {
  await finish(browser, h.results)
}
